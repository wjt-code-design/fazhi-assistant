// 每日法条随机轮播：以当天日期为种子确定性洗牌（每天牌面不同），
// 初始索引与每次 5 秒切换均为真随机，避免同一天内固定递增循环的规律感
export function _dailySeed() {
  const d = new Date();
  return d.getFullYear() * 10000 + (d.getMonth() + 1) * 100 + d.getDate();
}
export function _shuffleBySeed(arr: DailyLaw[], seed: number): DailyLaw[] {
  const a = [...arr];
  let s = seed;
  for (let i = a.length - 1; i > 0; i--) {
    s = (s * 9301 + 49297) % 233280;
    const j = s % (i + 1);
    [a[i], a[j]] = [a[j], a[i]];
  }
  return a;
}
export const DAILY_LAWS = _shuffleBySeed(RAW_DAILY_LAWS, _dailySeed());
export function dailyLawIndex() {
  return Math.floor(Math.random() * DAILY_LAWS.length);
}

